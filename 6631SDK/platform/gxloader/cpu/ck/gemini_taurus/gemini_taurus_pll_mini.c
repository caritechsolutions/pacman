static void stage1_data_reverse(unsigned char *val, unsigned int size)
{
	int i = 0;
	unsigned char tmp_val;
	for(i = 0; i < size / 2; i++) {
		tmp_val = val[i];
		val[i] = val[size - i - 1];
		val[size - i - 1] = tmp_val;
	}
}

static int stage1_strncmp(const char *cs, const char *ct, unsigned int count)
{
	unsigned char c1, c2;

	while (count) {
		c1 = *cs++;
		c2 = *ct++;
		if (c1 != c2)
			return c1 < c2 ? -1 : 1;
		if (!c1)
			break;
		count--;
	}
	return 0;
}

