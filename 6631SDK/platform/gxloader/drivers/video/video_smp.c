int video_SMP_config(int mem_type, int id, unsigned int addr, int size)
{
	int ret = -1;
	int i = 0;
	unsigned data = 0;
	unsigned short *head = (unsigned short *)bitcode_head;

	if (mem_type == GXMEM_FLAG_VIDEO_FIRMWARE) {
		for (i = 0; i < (sizeof(bitcode_head)/sizeof(unsigned short)); i++) {
			data = head[i];
			__raw_writel(((i << 16) | data), VDEC_CODE_DOWN);
		}

		__raw_writel(size, VDEC_CODE_BUF_SIZE);
		__raw_writel(addr, VDEC_CODE_BUF_ADDR);

		__raw_writel(0, VDEC_INT_ENABLE);
		//set VDEC buffer protect ready
		REG_SET_BIT(VDEC_CODE_RUN, 0);

		ret = 0;
	}
	return ret;
}

