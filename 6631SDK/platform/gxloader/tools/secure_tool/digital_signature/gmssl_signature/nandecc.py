def nand_bin_add_ecc(input, input_len, page_size):
    if input_len % 512:
        raise ValueError("stage1 size should be align 512")

    if page_size != 2048 and page_size != 4096:
        raise ValueError("page size error, is not 2048 or 4096 !")

    ff = bytearray(512)  # 定义一个512字节的数组
    ff[:] = [0xFF] * 512  # 将数组的所有元素赋值为0xFF
    ff_ecc = bytearray(28)
    nand_ecc_cal(ff, 512, 28, ff_ecc)

    readlen = 0
    writelen = 0
    subpage_count = 0
    ecc = bytearray(28)
    buf_ecc = bytearray(input_len * 16)
    buf_ecc[:] = [0xFF] * (input_len * 16)
    while readlen < input_len:
        nand_ecc_cal(input[readlen:readlen+512], 512, 28, ecc)
        buf_ecc[writelen:writelen+512] = input[readlen:readlen+512]
        readlen += 512
        writelen += 512
        for i in range(28):
            ecc[i] = ~(ecc[i] ^ ff_ecc[i]) & 0xff
        buf_ecc[writelen:writelen+28] = ecc[:28]
        writelen += 28
        subpage_count += 1
        if subpage_count == 2:
            subpage_count = 0
            page_pad_len = page_size - writelen % page_size
            writelen += page_pad_len

    return buf_ecc, writelen

def nand_bin_remove_ecc(input, input_len, page_size):
    if input_len % 512:
        raise ValueError("stage1 size should be align 512")

    if page_size != 2048 and page_size != 4096:
        raise ValueError("page size error, is not 2048 or 4096 !")

    readlen = 0
    writelen = 0
    subpage_count = 0
    output = bytearray(input_len)
    while readlen < input_len:
        output[writelen:writelen+512] = input[readlen:readlen+512]
        writelen += 512
        readlen += (512+28)
        subpage_count += 1
        if(subpage_count) == 2:
            subpage_count = 0
            page_pad_len = page_size - readlen % page_size
            readlen += page_pad_len

    return output, writelen

