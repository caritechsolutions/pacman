// for message notify
void app_cgcas_show_long_message_notify(void* p)
{
    static Cascam_CGShowLongMessage cgcas_long_msg;
    CascamUiNoticeClass ui_notice;

    if (NULL == p)
    {
        printf("%s,%d, data is NULL!\n", __func__, __LINE__);
        return ;
    }

    memset(&cgcas_long_msg, 0, sizeof(Cascam_CGShowLongMessage));
    memcpy(&cgcas_long_msg, p, sizeof(Cascam_CGShowLongMessage));

    memset(&ui_notice, 0, sizeof(CascamUiNoticeClass));
    ui_notice.timeout_sec = cgcas_long_msg.lmsgDuration;
    ui_notice.str = (char *)cgcas_long_msg.lmsgText;

    cascam_ui_exit_long_msg_ex_dialog();
    cascam_ui_create_long_msg_ex_dialog(&ui_notice, cgcas_long_msg.lmsgForced);
}

void app_cgcas_hide_long_message_notify(void* p)
{
    if(NULL == p)
    {
        printf("%s,%d, data is NULL!\n", __func__, __LINE__);
        return ;
    }

    cascam_ui_exit_msg_ex_dialog();
}

