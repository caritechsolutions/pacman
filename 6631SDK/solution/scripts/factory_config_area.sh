# Generate Config.in file for area config
##############################################################################
BUILD_DIR=$(pwd)
config_area_conf=${BUILD_DIR}/system/configin/Config.in.area
config_area_file=${BUILD_DIR}/scripts/area_config
if [ ! -e $config_area_file ];then
	echo "Cannot find area_config: $config_area_file"
	exit 0
fi

#echo $config_area_file
##############################################################################
# Output area Config
##############################################################################
config_area_short=` grep "AREA" $config_area_file |  awk -F '[\t]' '{if($2=="=y") print($3)}' `
config_area_list=` grep "AREA" $config_area_file |  awk -F '[\t]' '{if($2=="=y") print($4)}' | awk -F ',' '{print($1)}' |awk -F '"' '{print($2)}'|awk -F ' ' '{for(i=1;i<=NF;i++) {if(i!=NF) printf $i"_";else print $i}}'`
if [[ ${config_area_list} == "" ]]; then
	echo "Cannot find any area  config file"
	exit 1
fi

echo "area List:"
echo "     "$config_area_list
echo ""

echo "#This File is generated by script tools, please not modify by hands." > $config_area_conf
echo "" >> $config_area_conf

echo "menu \"Area Config\"" >> $config_area_conf
echo "" >> $config_area_conf
area_short_array=(${config_area_short})
area_list_array=(${config_area_list})
area_count=${#area_list_array[*]}
# output area config
for i in `seq 0 $((area_count-1))`
do
	each_area_upper=`echo ${area_list_array[i]} | tr [:lower:] [:upper:]`
	each_area_short_upper=`echo ${area_short_array[i]} | tr [:lower:] [:upper:]`
	echo "config BR2_AREA_${each_area_short_upper}_${each_area_upper}" >> $config_area_conf
	area_seprate=`echo ${area_list_array[i]}|awk -F '_' '{for(i=1;i<=NF;i++) {if(i!=NF) printf $i" ";else print $i}}'`
	echo "    bool \"${area_seprate}\"" >> $config_area_conf
	echo "    default y">> $config_area_conf
	echo "" >> $config_area_conf
done

echo "" >> $config_area_conf
echo "choice" >> $config_area_conf
echo "    prompt \"Default area\"" >> $config_area_conf
echo "" >> $config_area_conf

# output default lauange config
for i in `seq 0 $((area_count-1))`
do
	each_area_upper=`echo ${area_list_array[i]} | tr [:lower:] [:upper:]`
	each_area_short_upper=`echo ${area_short_array[i]} | tr [:lower:] [:upper:]`
	echo "config BR2_AREA_DEFAULT_${each_area_short_upper}_${each_area_upper}" >> $config_area_conf
	area_seprate=`echo ${area_list_array[i]}|awk -F '_' '{for(i=1;i<=NF;i++) {if(i!=NF) printf $i" ";else print $i}}'`
	echo "    bool \"${area_seprate}\"" >> $config_area_conf
	echo "    depends on BR2_AREA_${each_area_short_upper}_${each_area_upper}" >> $config_area_conf
	echo "" >> $config_area_conf
done

echo "endchoice" >> $config_area_conf

echo "endmenu" >> $config_area_conf
echo "" >> $config_area_conf
