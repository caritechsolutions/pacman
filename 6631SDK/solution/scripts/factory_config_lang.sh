# Generate Config.in file for language config
##############################################################################

proj_theme_name=$1

BUILD_DIR=$(pwd)
config_lang_conf=${BUILD_DIR}/system/configin/Config.in.osd_lang.${proj_theme_name}
config_kb_lang_conf=${BUILD_DIR}/system/configin/Config.in.kb_lang.${proj_theme_name}
config_theme_path=${BUILD_DIR}/theme/${proj_theme_name}
config_lang_path=${config_theme_path}/language
if [ ! -e $config_theme_path ];then
	echo "Cannot find theme path: $config_theme_path"
	exit 1
fi
#echo $config_lang_path
##############################################################################
# Output Lanuage Config
##############################################################################
#config_lang_list=` find $config_lang_path -name "*.xml" | awk '{cmdstr="basename "$0;system(cmdstr);}'|grep -v "i18n" |awk -F"." '{print $1}'`
config_lang_list=` ls -l $config_lang_path/*.xml | awk '{cmdstr="basename "$NF;system(cmdstr);}'|grep -v "i18n\|keyboard" |awk -F"." '{print $1}'`

if [[ ${config_lang_list} == "" ]]; then
	echo "Cannot find any language XML file"
	exit 1
fi

echo "Theme: ${proj_theme_name}"
echo "Language List:"
echo "     "$config_lang_list
echo ""

echo "#This File is generated by script tools, please not modify by hands." > $config_lang_conf
echo "" >> $config_lang_conf

echo "menu \"OSD Language Config\"" >> $config_lang_conf
echo "" >> $config_lang_conf

# output lanauge config
for each_lang in $config_lang_list
do
	each_lang_upper=`echo ${each_lang} | tr [:lower:] [:upper:]`
	echo "config BR2_LANG_${proj_theme_name}_${each_lang_upper}" >> $config_lang_conf
	echo "    bool \"${each_lang}\"" >> $config_lang_conf
	echo "" >> $config_lang_conf
done

echo "" >> $config_lang_conf
echo "choice" >> $config_lang_conf
echo "    prompt \"Default language\"" >> $config_lang_conf
echo "" >> $config_lang_conf

# output default lauange config
for each_lang in $config_lang_list
do
	each_lang_upper=`echo ${each_lang} | tr [:lower:] [:upper:]`
	echo "config BR2_LANG_DEFAULT_${proj_theme_name}_${each_lang_upper}" >> $config_lang_conf
	echo "    bool \"${each_lang}\"" >> $config_lang_conf
	echo "    depends on BR2_LANG_${proj_theme_name}_${each_lang_upper}" >> $config_lang_conf
	echo "" >> $config_lang_conf
done

echo "endchoice" >> $config_lang_conf

# add matrix vector font select
echo "" >> $config_lang_conf
echo "choice" >> $config_lang_conf
echo "    prompt \"Chinese font type\"" >> $config_lang_conf
echo "    depends on BR2_LANG_${proj_theme_name}_CHINESE" >> $config_lang_conf
echo "" >> $config_lang_conf

echo "config BR2_FONT_${proj_theme_name}_CHINESE_VECTOR" >> $config_lang_conf
echo "   bool \"Vector\"" >> $config_lang_conf
echo "    depends on BR2_LANG_${proj_theme_name}_CHINESE" >> $config_lang_conf
echo "" >> $config_lang_conf

echo "config BR2_FONT_${proj_theme_name}_CHINESE_MATRIX" >> $config_lang_conf
echo "    bool \"Matrix\"" >> $config_lang_conf
echo "    depends on BR2_LANG_${proj_theme_name}_CHINESE" >> $config_lang_conf
echo "" >> $config_lang_conf

echo "endchoice" >> $config_lang_conf

echo "" >> $config_lang_conf
echo "endmenu" >> $config_lang_conf

echo "" > $config_kb_lang_conf
config_kb_lang_list=$(grep -rn "language" $config_lang_path/keyboard.xml |cut -f 2 -d "\"")
if [[ ${config_kb_lang_list} == "" ]]; then
	echo "Cannot find keyboard_language XML file"
	exit 1
fi

echo "#This File is generated by script tools, please not modify by hands." > $config_kb_lang_conf
echo "" >> $config_kb_lang_conf

echo "menu \"KeyBorad Language Config\"" >> $config_kb_lang_conf
echo "" >> $config_kb_lang_conf

# output lanauge config
for each_lang in $config_kb_lang_list
do
	each_lang_upper=`echo ${each_lang} | tr [:lower:] [:upper:]`
	echo "config BR2_KB_LANG_${proj_theme_name}_${each_lang_upper}" >> $config_kb_lang_conf
	echo "    bool \"${each_lang}\"" >> $config_kb_lang_conf
	echo "" >> $config_kb_lang_conf
done



echo "choice" >> $config_kb_lang_conf
echo "    prompt \"Default KB language\"" >> $config_kb_lang_conf
echo "" >> $config_kb_lang_conf
# output default lauange config
for each_lang in $config_kb_lang_list
do
	each_lang_upper=`echo ${each_lang} | tr [:lower:] [:upper:]`
	echo "config BR2_KB_LANG_DEFAULT_${proj_theme_name}_${each_lang_upper}" >> $config_kb_lang_conf
	echo "    bool \"${each_lang}\"" >> $config_kb_lang_conf
	echo "    depends on BR2_KB_LANG_${proj_theme_name}_${each_lang_upper}" >> $config_kb_lang_conf
	echo "" >> $config_kb_lang_conf
done

echo "endchoice" >> $config_kb_lang_conf

echo "endmenu" >> $config_kb_lang_conf
echo "" >> $config_kb_lang_conf


