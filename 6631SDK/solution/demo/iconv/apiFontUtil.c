static uint16_t MApi_CharTable_MappinUCS2ToUCS2( uint8_t *pu8SrcStr, uint16_t *pu16DstStr, uint16_t srcByteLen, uint16_t dstWideCharLen )
{
    uint16_t u16Value;
    uint16_t i, j;

    if ( ( pu8SrcStr == 0 ) || ( srcByteLen == 0 ) || ( pu16DstStr == 0 ) || ( dstWideCharLen <= 1 ) )
    {
        return 0;
    }

    for ( i = 0, j = 0; i < srcByteLen - 1 && j < dstWideCharLen - 1; i += 2, j++ )
    {
        u16Value = ( pu8SrcStr[i] << 8 ) | pu8SrcStr[i + 1];
        if ( u16Value == 0x00 )
        {
            break;
        }
        else
        {
            pu16DstStr[j] = u16Value;
        }
        // convert control
        if ( pu16DstStr[j] >= 0x80 && pu16DstStr[j] <= 0x9F )
        {
            pu16DstStr[j] = ( 0xE000 | pu16DstStr[j] );
        }
    }

    // NULL termination character
    pu16DstStr[j] = 0;

    return j;
}

//*************************************************************************
//Function name:
//Passing parameter:
//Return parameter:
//Description:
//*************************************************************************
static int16_t MApi_CharTable_BinarySearch( uint16_t table[][2], int16_t min, int16_t max, uint16_t key )
{
    //see reference from http://en.wikipedia.org/wiki/Binary_search
    uint16_t high,low,i;
    if (min <= 0)
    {
        min = 0;
    }
    else
    {
        min=min-1;
    }

    if (key == 0xC141) return 0;

    for ( low = min, high = max; high - low > 1; )
    {
        i = ( high + low ) / 2;
        if ( key <= table[i][1] )
        {
            high = i;
        }
        else
        {
            low = i;
        }
    }
    if ( key == table[high][1] )
    {
        return high;
    }
    else
    {
        return -1;
    }
}

static uint16_t MApi_CharTable_PostProcess( uint16_t *pu16Str, uint16_t u16WideCharLen, uint16_t filterCtrl )
{
    uint16_t i,j;

    if ( ( pu16Str == 0 ) || ( u16WideCharLen == 0 ) )
    {
        return 0;
    }

    j = 0;
    if ( filterCtrl )
    {
        for ( i = 0; i < u16WideCharLen; i++ )
        {
            if ( ( filterCtrl & REMOVE_00AD_SOFT_HYPHEN ) && pu16Str[i] == 0x00AD )
            {
                j++;
            }
            else if ( j )
            {
                pu16Str[i - j] = pu16Str[i];
            }
        }
        pu16Str[u16WideCharLen - j] = 0;
    }
    return ( u16WideCharLen - j );
}


