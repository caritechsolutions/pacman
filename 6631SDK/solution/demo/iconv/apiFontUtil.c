uint16_t MApi_CharTable_MappingIsoToUCS2( EN_CHARACTER_CODE_TABLE enTable, uint8_t *pu8Str, uint16_t *pu16Str, uint16_t srcByteLen, uint16_t dstWideCharLen )
{
    uint8_t  u8Value;
    uint16_t i;

    if ( ( pu8Str == 0 ) || ( srcByteLen == 0 ) || ( pu16Str == 0 ) || ( dstWideCharLen <= 1 ) )
    {
        return 0;
    }

    if ( enTable == ISO_6937 )
    {
        return MApi_CharTable_MappingIso6937ToUCS2( pu8Str, pu16Str, srcByteLen, dstWideCharLen );
    }

    for ( i = 0; i < srcByteLen && i < dstWideCharLen - 1; i++ )
    {
        u8Value = pu8Str[i];
        if ( u8Value == 0x00 )
        {
            break;
        }
        else if ( u8Value < 0x80 )
        {
            pu16Str[i] = ( uint16_t )u8Value;
        }
        else
        {
            pu16Str[i] = ISO_CHARACTER_TABLES[enTable][u8Value - 0x80];
        }
        // convert control
        if ( pu16Str[i] >= 0x80 && pu16Str[i] <= 0x9F )
        {
            pu16Str[i] = ( 0xE000 | pu16Str[i] );
        }
    }

    // NULL termination character
    pu16Str[i] = 0;

    return i;
}

