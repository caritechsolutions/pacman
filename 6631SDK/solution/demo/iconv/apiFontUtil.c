/// @brief The function convert UTF8 string to UCS2 string
/// @param[in] pu8Str the pointer point to the UTF8 string buffer
/// @param[in] pu16Str the pointer point to the UCS2 string buffer
/// @param[in] srcByteLen scouce string length
/// @param[in] dstWideCharLen destination string buffer size
/// @return the string length after convertion
//------------------------------------------------------------------------------
uint16_t MApi_CharTable_MappinUTF8ToUCS2( uint8_t *pu8Str, uint16_t *pu16Str, uint16_t srcByteLen, uint16_t dstWideCharLen )
{
    //see reference from http://en.wikipedia.org/wiki/Utf-8
    uint8_t  u8Value;
    uint16_t i, j;

    if ( ( pu8Str == 0 ) || ( srcByteLen == 0 ) || ( pu16Str == 0 ) || ( dstWideCharLen <= 1 ) )
    {
        return 0;
    }

    for ( i = 0, j = 0; i < srcByteLen && j < dstWideCharLen - 1; i++, j++ )
    {
        u8Value = pu8Str[i];
        if ( u8Value == 0 )
        {
            break;
        }
        if ( ( u8Value & 0x80 ) == 0 )
        {
            // 0zzzzzzz(00-7F) => 00000000 0zzzzzzz
            pu16Str[j] = ( uint16_t )( u8Value & 0x7F );
        }
        else if ( ( ( u8Value & 0xE0 ) == 0xC0 ) && ( ( i + 1 ) < srcByteLen ) )
        {
            // 110yyyyy(C2-DF) 10zzzzzz(80-BF) => 00000yyy yyzzzzzz
            pu16Str[j] = ( uint16_t )( ( ( u8Value & 0x1F ) << 6 ) | ( pu8Str[i + 1] & 0x3F ) );
        }
        else if ( ( ( u8Value & 0xF0 ) == 0xE0 ) && ( ( i + 2 ) < srcByteLen ) )
        {
            // 1110xxxx(E0-EF) 10yyyyyy 10zzzzzz => xxxxyyyy yyzzzzzz
            pu16Str[j] = ( uint16_t )( ( ( u8Value & 0xF ) << 12 ) | ( ( pu8Str[i + 1] & 0x3F ) << 6 ) | ( pu8Str[i + 2] & 0x3F ) );
        }
        else
        {
            // Unknown, skip
            j--;
            continue;
        }

        // convert control
        if ( pu16Str[j] >= 0x80 && pu16Str[j] <= 0x9F )
        {
            pu16Str[j] = ( 0xE000 | pu16Str[j] );
        }
    }

    // NULL termination character
    pu16Str[j] = 0;

    return j;
}


