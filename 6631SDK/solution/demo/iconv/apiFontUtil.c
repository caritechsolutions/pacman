static uint16_t _FONT_binary_serach_table(uint16_t target, const uint16_t *unicode_table, int32_t items)
{
    int32_t index_head, index_mid, index_tail;

    index_head = 0;
    index_tail = items>>1;
    index_mid = (index_head+index_tail)>>1;

    //Binary search
    while((index_head <= index_tail) && (unicode_table[index_mid<<1] != target) && index_tail)
    {
        // is the target in lower or upper half?
        if (target < unicode_table[index_mid<<1])
        {
            index_tail = index_mid - 1;                 // new end
            index_mid = (index_head+index_tail)>>1;     // new middle
        }
        else
        {
            index_head = index_mid + 1;                 // new beginning
            index_mid = (index_head+index_tail)>>1;     // new middle
        }
    }

    //Find the target?
    if (unicode_table[index_mid<<1] == target)
    {
        return unicode_table[(index_mid<<1)+1];
    }
    else
    {
        return 0;
    }

}

uint8_t FONT_ascii_2_unicode(uint16_t *out, uint8_t *in)
{
    uint8_t c1 = *in;

    if (c1 < 0x80)
    {
        *out = (uint16_t)c1;
        return 1;
    }
    return 0;
}

uint8_t FONT_big5_2_unicode(uint16_t *out, uint8_t *in)
{
    uint8_t c1 = in[0];
    uint8_t c2 = in[1];
    uint16_t big5 = (c1<<8)+c2;
    uint16_t wc = 0xfffd;

    if (((c1 >= 0xa1 && c1 <= 0xc7) || (c1 >= 0xc9 && c1 <= 0xf9)) &&
        ((c2 >= 0x40 && c2 <  0x7f) || (c2 >= 0xa1 && c2 <  0xff)) )
    {
        wc =  _FONT_binary_serach_table(big5, big5_2_unicode, sizeof(big5_2_unicode)/sizeof(uint16_t));

        if (wc != 0xfffd)
        {
            *out = (uint16_t) wc;
            return 2;   //OK (2Byte)
        }
    }
    return 0;   //Fail
}

uint8_t FONT_ces_big5_2_unicode(uint16_t *out, uint8_t *in)
{
    uint8_t c = *in;

    // ASCII
    if (c < 0x80)
        return FONT_ascii_2_unicode(out, in);

    // big5
    if (c >= 0xa1 && c < 0xff)
    {
        return FONT_big5_2_unicode(out, in);
    }
    return 0;
}

